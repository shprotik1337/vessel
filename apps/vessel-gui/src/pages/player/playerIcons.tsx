export function getPlatformColor(provider?: string): string {
  switch (provider?.toLowerCase()) {
    case "soundcloud":
      return "#ff5500";
    case "spotify":
      return "#1ed760";
    case "you_tube_music":
    case "youtube":
      return "#ff0000";
    case "deezer":
      return "#a238ff";
    case "yandex":
      return "#fc3f1d";
    case "vk":
      return "#0077ff";
    case "apple_music":
    case "apple":
      return "#fc3c44";
    default:
      return "var(--accent, #6366f1)";
  }
}
